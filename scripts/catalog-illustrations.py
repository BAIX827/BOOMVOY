"""Validate local masters/exports, build a portable index and optionally archive them.

Run after prepare-illustrations.py. Requires Pillow. No network or cloud writes.
"""
import argparse
import hashlib
import html
import json
import zipfile
from pathlib import Path
from PIL import Image

ROOT = Path(__file__).resolve().parents[1]
parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument('--archive', action='store_true', help='Create and verify a local ZIP snapshot')
args = parser.parse_args()
local_manifest = ROOT / 'output/illustration-masters/generation.json'
public_manifest = ROOT / 'docs/illustration-generation.json'
generation_file = local_manifest if local_manifest.exists() else public_manifest
generation = json.loads(generation_file.read_text(encoding='utf-8'))
if local_manifest.exists():
    portable = {**generation, 'assets': [
        {key: value for key, value in entry.items() if key not in ('source', 'originalSource')}
        for entry in generation['assets']
    ]}
    public_manifest.write_text(json.dumps(portable, ensure_ascii=False, indent=2) + '\n', encoding='utf-8')
assets = []
seen = set()


def file_record(path):
    with Image.open(path) as image:
        assert 'A' in image.getbands(), f'Missing alpha channel: {path}'
        alpha_min, alpha_max = image.getchannel('A').getextrema()
        # Watercolor masters can peak at 254; a valid alpha channel need not reach exactly 255.
        assert alpha_min == 0 and alpha_max >= 250, f'Invalid transparency: {path}'
        width, height = image.size
    return {'path': path.relative_to(ROOT).as_posix(), 'bytes': path.stat().st_size,
            'sha256': hashlib.sha256(path.read_bytes()).hexdigest(), 'width': width, 'height': height}


for source in generation['assets']:
    asset_id, kind, version = source['id'], source['kind'], source.get('version', 1)
    assert (asset_id, version) not in seen, f'Duplicate asset: {asset_id} v{version}'
    seen.add((asset_id, version))
    master = file_record(ROOT / f'output/illustration-masters/{asset_id}-v{version}.png')
    web = file_record(ROOT / f'src/assets/illustrations/{kind}/{asset_id}-v{version}.webp')
    web480 = file_record(ROOT / f'src/assets/illustrations/{kind}/{asset_id}-v{version}-480.webp')
    assert web['width'] <= 960 and web['height'] <= 640, f'Oversized export: {asset_id}'
    assert web['width'] == 960 and web480['width'] == 480, f'Srcset width mismatch: {asset_id}'
    assert web480['height'] <= 320 and web480['bytes'] < 120_000, f'Oversized small export: {asset_id}'
    assert web['bytes'] < 300_000, f'Review web asset size: {asset_id}'
    prefix = f'boomvoy/illustrations/v{version}/{kind}/{asset_id}'
    assets.append({'id': asset_id, 'kind': kind, 'version': version, 'name': source['name'],
                   'country': source['country'], 'region': source['region'], 'master': master, 'web': web, 'web480': web480,
                   'provenance': {'tool': generation['tool'], 'date': source.get('date', generation['date']),
                                  'prompt': source['prompt'],
                                  'styleReference': source.get('styleReference', generation['reference']),
                                  'refinement': source.get('refinement')},
                   'suggestedObjectKeys': {'master': f'{prefix}/master.png', 'web': f'{prefix}/web.webp', 'web480': f'{prefix}/web-480.webp'}})

totals = {'count': len(assets), 'masterBytes': sum(a['master']['bytes'] for a in assets),
          'webBytes': sum(a['web']['bytes'] for a in assets), 'web480Bytes': sum(a['web480']['bytes'] for a in assets)}
inventory = {'schemaVersion': 2, 'storageStatus': 'local archive; cloud backup deferred by user',
             'totals': totals, 'assets': assets}
manifest = ROOT / 'docs/illustration-assets.json'
manifest.write_text(json.dumps(inventory, ensure_ascii=False, indent=2) + '\n', encoding='utf-8')
destinations = [{'id': a['id'], 'kind': a['kind'], 'city': 'Cairo' if a['id'] == 'cairo' else a['name']['en'], 'name': a['name']} for a in assets if a['kind'] != 'generic']
runtime_catalog = ROOT / 'src/illustrationDestinations.ts'
runtime_catalog.write_text('// Generated by scripts/catalog-illustrations.py; edit generation.json instead.\n'
                           + 'export const ILLUSTRATION_DESTINATIONS = ' + json.dumps(destinations, ensure_ascii=False, indent=2) + ' as const\n', encoding='utf-8')
landmark_catalog = ROOT / 'src/illustrationLandmarks.ts'
landmarks = [{'id': a['id'], 'aliases': list(dict.fromkeys([a['name']['zh'], a['name']['en'], *a.get('aliases', [])]))} for a in generation['assets'] if a['kind'] == 'landmarks']
landmark_catalog.write_text('// Generated by scripts/catalog-illustrations.py; edit generation.json instead.\n'
                           + 'export const LANDMARK_ILLUSTRATIONS = ' + json.dumps(landmarks, ensure_ascii=False, indent=2) + ' as const\n', encoding='utf-8')

regions = {'oceania': '大洋洲', 'asia': '亚洲', 'europe': '欧洲', 'europe-asia': '欧洲／亚洲',
           'north-america': '北美洲', 'south-america': '南美洲', 'africa': '非洲', 'generic': '通用风景'}
cards = []
for a in reversed(assets):
    title = html.escape(a['name']['zh'])
    english = html.escape(a['name']['en'])
    search = html.escape(' '.join([a['id'], a['name']['zh'], a['name']['en'], a['country'] or '', regions[a['region']]]), quote=True)
    cards.append(f'''<article data-search="{search}" data-region="{a['region']}" data-kind="{a['kind']}">
<div class="art"><img src="../../{a['web480']['path']}" srcset="../../{a['web480']['path']} 480w, ../../{a['web']['path']} 960w" sizes="auto, (max-width:560px) calc(100vw - 66px), (max-width:900px) 40vw, 360px" alt="{title}插画" loading="lazy" width="960" height="640"></div>
<h2>{title} <small>v{a['version']}</small></h2><p>{english} · {regions[a['region']]}</p>
<p class="size">小图 {a['web480']['bytes'] / 1024:.0f} KiB · 大图 {a['web']['bytes'] / 1024:.0f} KiB · 母版 {a['master']['bytes'] / 1_000_000:.2f} MB</p>
<nav aria-label="{title}文件"><a href="../../{a['web480']['path']}" download>480px WebP</a><a href="../../{a['web']['path']}" download>960px WebP</a><a href="../../{a['master']['path']}" download>PNG 母版</a></nav>
<details><summary>提示词与校验值</summary><p>{html.escape(a['provenance']['prompt'])}</p><p>{html.escape(a['provenance']['refinement'] or '')}</p><p class="hash">480px SHA-256: {a['web480']['sha256']}</p><p class="hash">960px SHA-256: {a['web']['sha256']}</p><p class="hash">PNG SHA-256: {a['master']['sha256']}</p></details></article>''')
options = ''.join(f'<option value="{key}">{value}</option>' for key, value in regions.items())
page = '''<!doctype html><html lang="zh-CN"><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1">
<title>BOOMVOY 素材目录</title><style>
*{box-sizing:border-box}body{margin:0;background:#f5f1e7;color:#263950;font:16px/1.6 system-ui,sans-serif}main{max-width:1240px;margin:auto;padding:32px 24px}h1{font-size:30px;margin:0}header p{max-width:780px}.controls{display:flex;gap:12px;flex-wrap:wrap;padding:16px 0}label{display:flex;align-items:center;gap:8px}input,select{font:inherit;padding:10px;border:1px solid #a5aa9e;border-radius:6px;background:#fffdf7;min-height:44px}input{width:260px;max-width:100%}.grid{display:grid;grid-template-columns:repeat(3,minmax(0,1fr));gap:20px}article{min-width:0;background:#fffdf7;border:1px solid #ddd8ca;padding:16px;border-radius:8px}article[hidden]{display:none}.art{background:linear-gradient(45deg,#e8e5db 25%,transparent 25%,transparent 75%,#e8e5db 75%),linear-gradient(45deg,#e8e5db 25%,#f8f6ef 25%,#f8f6ef 75%,#e8e5db 75%);background-size:20px 20px;background-position:0 0,10px 10px;border-radius:4px}img{display:block;width:100%;height:180px;object-fit:contain}h2{font-size:19px;margin:12px 0 0}small,.size{font-size:13px;color:#576459}article p{margin:4px 0}nav{display:flex;gap:10px;flex-wrap:wrap;margin:12px 0}a{color:#263950;text-underline-offset:3px;display:inline-flex;align-items:center;min-height:44px}details{border-top:1px solid #ddd8ca;padding-top:10px}summary{cursor:pointer;min-height:44px;display:list-item}details p{font-size:13px}.hash{overflow-wrap:anywhere}#empty{padding:30px 0}footer{font-size:13px;color:#576459;margin-top:32px}@media(max-width:900px){.grid{grid-template-columns:repeat(2,minmax(0,1fr))}}@media(max-width:560px){main{padding:24px 16px}.grid{grid-template-columns:minmax(0,1fr)}label{width:100%;justify-content:space-between}input,select{flex:1;min-width:0}h1{font-size:26px}img{height:150px}}
</style><main><header><h1>BOOMVOY 素材目录</h1><p>海军蓝细线与淡水彩 · 透明背景 · 城市地标为概念式组合</p><p>__TOTALS__</p><p>此目录供素材整理与检查；母版已保存到项目。本地 ZIP 是迁移包，尚未验证异地备份。</p></header>
<div class="controls"><label>搜索 <input id="search" type="search" placeholder="城市、景点、国家或文件名"></label><label>地区 <select id="region"><option value="">全部地区</option>__OPTIONS__</select></label><label>类别 <select id="kind"><option value="">全部类别</option><option value="cities">城市与地区</option><option value="landmarks">著名景点</option><option value="generic">通用风景</option></select></label></div>
<p id="count" role="status" aria-live="polite"></p><div class="grid">__CARDS__</div><p id="empty" hidden>没有匹配的素材。</p><footer>由 scripts/catalog-illustrations.py 生成。修改源清单后重新运行；网页图片与母版有独立 SHA-256 记录。</footer></main>
<script>
const search=document.querySelector('#search'),region=document.querySelector('#region'),kind=document.querySelector('#kind'),cards=[...document.querySelectorAll('article')];
function filter(){const query=search.value.trim().toLocaleLowerCase();let count=0;for(const card of cards){card.hidden=!(card.dataset.search.toLocaleLowerCase().includes(query)&&(!region.value||card.dataset.region===region.value)&&(!kind.value||card.dataset.kind===kind.value));if(!card.hidden)count++;}document.querySelector('#count').textContent=`显示 ${count} / ${cards.length} 张`;document.querySelector('#empty').hidden=count>0;}
search.addEventListener('input',filter);region.addEventListener('change',filter);kind.addEventListener('change',filter);filter();
</script></html>'''
page = page.replace('__TOTALS__', f"共 {totals['count']} 张 · PNG 母版 {totals['masterBytes'] / 1_000_000:.2f} MB · 960px WebP {totals['webBytes'] / 1_000_000:.2f} MB · 480px WebP {totals['web480Bytes'] / 1_000_000:.2f} MB")
page = page.replace('__OPTIONS__', options).replace('__CARDS__', '\n'.join(cards))
gallery = ROOT / 'output/illustration-library/index.html'
gallery.parent.mkdir(parents=True, exist_ok=True)
gallery.write_text(page, encoding='utf-8')
print(json.dumps(totals))

if args.archive:
    paths = {manifest, gallery, runtime_catalog, landmark_catalog, generation_file, public_manifest,
             ROOT / 'scripts/prepare-illustrations.py', ROOT / 'scripts/catalog-illustrations.py',
             ROOT / 'scripts/verify-illustration-archive.py',
             ROOT / 'docs/ASSET_STORAGE.md'}
    paths.update((ROOT / 'docs/illustration-prompts').glob('*.md'))
    for a in assets:
        paths.update([ROOT / a[kind]['path'] for kind in ['master', 'web', 'web480']])
    # Include metadata and scripts too: each changed snapshot gets a new name.
    snapshot_hash = hashlib.sha256()
    for path in sorted(paths):
        snapshot_hash.update(path.relative_to(ROOT).as_posix().encode('utf-8'))
        snapshot_hash.update(hashlib.sha256(path.read_bytes()).digest())
    archive = ROOT / f'output/asset-archives/boomvoy-illustrations-{snapshot_hash.hexdigest()[:12]}.zip'
    archive.parent.mkdir(parents=True, exist_ok=True)
    with zipfile.ZipFile(archive, 'w', compression=zipfile.ZIP_STORED) as bundle:
        for path in sorted(paths):
            info = zipfile.ZipInfo(path.relative_to(ROOT).as_posix(), tuple(int(part) for part in generation['date'].split('-')) + (0, 0, 0))
            info.compress_type = zipfile.ZIP_STORED
            bundle.writestr(info, path.read_bytes())
    with zipfile.ZipFile(archive) as bundle:
        assert bundle.testzip() is None, 'ZIP CRC verification failed'
        for a in assets:
            for kind in ['master', 'web', 'web480']:
                record = a[kind]
                assert hashlib.sha256(bundle.read(record['path'])).hexdigest() == record['sha256']
    checksum = hashlib.sha256(archive.read_bytes()).hexdigest()
    archive.with_suffix('.zip.sha256').write_text(f'{checksum}  {archive.name}\n', encoding='ascii')
    receipt = {'schemaVersion': 1, 'status': 'local-archive-verified; cloud-backup-deferred',
               'archivePath': archive.relative_to(ROOT).as_posix(), 'sha256': checksum,
               'bytes': archive.stat().st_size, 'assetCount': len(assets), 'imageFileCount': len(assets) * 3,
               'inventorySha256': hashlib.sha256(manifest.read_bytes()).hexdigest()}
    (ROOT / 'docs/illustration-archive.json').write_text(json.dumps(receipt, ensure_ascii=False, indent=2) + '\n', encoding='utf-8')
    print(f'Verified archive: {archive.relative_to(ROOT)} ({archive.stat().st_size} bytes)')
