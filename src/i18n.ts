type Msg = keyof typeof zh

function fill(s: string, vars?: Vars) {
  if (!vars) return s
  return s.replace(/\{(\w+)\}/g, (_, k: string) => String(vars[k] ?? ''))
}

export function resolveLocale(raw?: string): Locale {
  return raw === 'en' ? 'en' : 'zh'
}

export function t(locale: Locale, key: string, vars?: Vars) {
  const table = locale === 'en' ? en : zh
  const raw = table[key as Msg] ?? zh[key as Msg] ?? key
  return fill(raw, vars)
}

export function useT() {
  const locale = useApp((s) => resolveLocale(s.profile.locale))
  const translate = useCallback((key: string, vars?: Vars) => t(locale, key, vars), [locale])
  return { locale, t: translate }
}

